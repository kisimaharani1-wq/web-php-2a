<?php
// FOR: dipakai kalau sudah tahu mau berapa kali
echo "<h3>Pakai for</h3>";
for ($i = 1; $i <= 5; $i++) {
    echo "Perulangan ke-" . $i . "<br>";
}

// WHILE: ulangi selama kondisinya masih benar
echo "<h3>Pakai while</h3>";
$j = 1;
while ($j <= 5) {
    echo "Hitungan ke-" . $j . "<br>";
    $j++;
}
?>